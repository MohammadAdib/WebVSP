"""Generate gl_stub.c: do-nothing definitions of the OpenGL/GLU/GLEW functions OpenVSP and FLTK
reference, for the in-browser engine.

In the browser OpenVSP's GUI is mirrored to the page and never draws with OpenGL (the 3D view
is the page's own; the GL views it mirrors send their draw objects instead). These stubs
satisfy the linker and make any incidental GL call harmless. Each stub takes its prototype
from Emscripten's GL headers (signatures must match exactly in WebAssembly), and the stub
file includes those headers, so the compiler checks them.

    python gen_gl_stub.py <emscripten sysroot include dir> <symbols file> > gl_stub.c

The symbols file lists the names, one per line, e.g. from
    llvm-nm -u <the .a files> | grep -E ' (gl|glu|glew)[A-Za-z0-9_]*$'
Re-run when the link reports a new undefined GL symbol.
"""

import re
import sys
from pathlib import Path

inc = Path(sys.argv[1])
names = [n.strip() for n in Path(sys.argv[2]).read_text().split() if n.strip()]
headers = "\n".join((inc / "GL" / h).read_text(errors="replace") for h in ("gl.h", "glext.h", "glu.h", "glew.h"))
headers = re.sub(r"/\*.*?\*/", " ", headers, flags=re.S)

# Bodies for functions whose callers read what they return or write.
SPECIAL = {
    "glGetString": 'static const GLubyte s[] = "WebVSP (no OpenGL)"; (void)name; return s;',
    "glewInit": "return 0; /* GLEW_OK */",
    "glewIsSupported": "(void)name; return GL_FALSE;",
    "glewGetErrorString": 'static const GLubyte s[] = ""; (void)error; return s;',
    "glGetIntegerv": "stub_fill_i(pname, PARAM1);",
    "glGetFloatv": "stub_fill_f(pname, PARAM1);",
    "glGetDoublev": "stub_fill_d(pname, PARAM1);",
    "glGetShaderiv": "(void)shader; (void)pname; if (params) *params = GL_TRUE;",
    "glGetProgramiv": "(void)program; (void)pname; if (params) *params = GL_TRUE;",
    "glGetShaderInfoLog": "(void)shader; if (length) *length = 0; if (infoLog && bufSize > 0) infoLog[0] = 0;",
    "glGetProgramInfoLog": "(void)program; if (length) *length = 0; if (infoLog && bufSize > 0) infoLog[0] = 0;",
    "glGetTexLevelParameteriv": "(void)target; (void)level; (void)pname; if (params) *params = 0;",
    "glCreateShader": "(void)type; return ++stub_next_id;",
    "glCreateProgram": "return ++stub_next_id;",
    "glGetUniformLocation": "(void)program; (void)name; return 0;",
    "gluUnProject": "(void)winX; (void)winY; (void)winZ; (void)model; (void)proj; (void)view;"
                    " *objX = *objY = *objZ = 0; return GL_TRUE;",
}
for gen in ("glGenBuffers", "glGenTextures", "glGenFramebuffers", "glGenRenderbuffers"):
    SPECIAL[gen] = "stub_gen(n, PARAM1);"


def prototype(name):
    # The declaration: from the previous ';', '}', '#' line or blank line up to the next ';'.
    for m in re.finditer(r"\b" + re.escape(name) + r"\s*\(", headers):
        start = max(headers.rfind(";", 0, m.start()), headers.rfind("}", 0, m.start()),
                    headers.rfind("\n#", 0, m.start()), headers.rfind("{", 0, m.start()))
        decl_head = headers[start + 1:m.start()]
        if "#" in decl_head.split("\n", 1)[0]:
            decl_head = decl_head.split("\n", 1)[1] if "\n" in decl_head else ""
        end = headers.find(";", m.end())
        close = headers.rfind(")", m.end(), end)
        if end < 0 or close < 0:
            continue
        ret = re.sub(r"\b(GLAPI|GLEWAPI|extern|GLAPIENTRY|APIENTRY)\b", "", decl_head)
        ret = " ".join(ret.split())
        if not ret or "define" in ret:
            continue  # a macro, not a declaration
        params = " ".join(headers[m.end():close].split())
        return ret, params
    raise SystemExit(f"no prototype for {name}")


out = [
    "// Generated by gen_gl_stub.py -- do not edit. See that script for what this is.",
    "#include <GL/glew.h>",
    "#include <GL/gl.h>",
    "#include <GL/glext.h>",
    "#include <GL/glu.h>",
    "#include <string.h>",
    "",
    "static GLuint stub_next_id = 0;",
    "static void stub_gen(GLsizei n, GLuint *ids) { for (GLsizei i = 0; i < n; i++) ids[i] = ++stub_next_id; }",
    "// Viewport/scissor boxes are 4 values, matrices 16 (identity); other queries 1 value (0).",
    "static int stub_count(GLenum p) { return (p == GL_VIEWPORT || p == GL_SCISSOR_BOX) ? 4 :",
    "  (p == GL_MODELVIEW_MATRIX || p == GL_PROJECTION_MATRIX || p == GL_TEXTURE_MATRIX) ? 16 : 1; }",
    "#define STUB_FILL(T) { int n = stub_count(pname); for (int i = 0; i < n; i++) data[i] = (T)((n == 16 && i % 5 == 0) ? 1 : 0); }",
    "static void stub_fill_i(GLenum pname, GLint *data) STUB_FILL(GLint)",
    "static void stub_fill_f(GLenum pname, GLfloat *data) STUB_FILL(GLfloat)",
    "static void stub_fill_d(GLenum pname, GLdouble *data) STUB_FILL(GLdouble)",
    "",
]
for name in names:
    ret, params = prototype(name)
    body = SPECIAL.get(name)
    if body and "PARAM1" in body:
        # The second parameter's name (the id array).
        body = body.replace("PARAM1", params.split(",")[1].split()[-1].lstrip("*"))
    if body is None:
        body = "" if ret == "void" else "return 0;"
    out.append(f"{ret} {name}({params or 'void'}) {{ {body} }}")
print("\n".join(out))
